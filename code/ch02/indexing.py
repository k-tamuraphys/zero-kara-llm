"""インデックスとスライス: テンソルの一部を取り出す。"""

import torch

# [snippet: basic]
A = torch.tensor([[0, 1, 2, 3],
                  [10, 11, 12, 13],
                  [20, 21, 22, 23]])  # 形 (3, 4)。十の位が行、一の位が列
print(A[1, 2], A[1, 2].item())  # 行 1・列 2 の要素。item() で Python の数に
print(A[1])  # 行 1 の全体。形 (4,)
print(A[:, 2])  # 「:」は「その軸は全部」。列 2 の全体。形 (3,)
print(A[0:2, 1:3])  # 行 0〜1、列 1〜2。形 (2, 2)
print(A[torch.tensor([2, 0])])  # 番号のテンソルで、行 2 と行 0 を取り出す
print(A[A > 20])  # 条件に合う要素だけを取り出す
# [end: basic]

print("---")
# [snippet: share]
row = A[0]  # スライスはコピーではなく、元のメモリをのぞく窓（ビュー）
row[0] = 99  # 窓ごしに書き換えると……
print(A[0])  # 元の A も変わっている
# [end: share]
